def desenhar_marca(canvas, largura_pagina, altura_pagina, margem, linha_sistema, pagina, cor):
    """Logotipo no canto superior esquerdo e rodapé institucional centralizado."""
    from reportlab.lib import colors
    largura_logo = 110
    altura_logo = largura_logo * 115 / 262
    canvas.saveState()
    canvas.drawImage(logo_reader(), margem, altura_pagina - 12 - altura_logo,
                     width=largura_logo, height=altura_logo, mask="auto")
    canvas.setStrokeColor(colors.HexColor("#D8E0EA"))
    canvas.setLineWidth(0.6)
    canvas.line(margem, 44, largura_pagina - margem, 44)
    canvas.setFillColor(cor)
    canvas.setFont("Helvetica", 7.5)
    canvas.drawCentredString(largura_pagina / 2, 34, ENDERECO)
    canvas.drawCentredString(largura_pagina / 2, 24, CONTATO)
    canvas.setFont("Helvetica", 6.5)
    canvas.drawString(margem, 12, linha_sistema)
    canvas.drawRightString(largura_pagina - margem, 12, pagina)
    canvas.restoreState()
